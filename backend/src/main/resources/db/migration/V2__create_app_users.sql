CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_users_login UNIQUE (login),
    CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'STAFF')),
    CONSTRAINT ck_app_users_login_nonempty CHECK (length(btrim(login)) > 0)
);
CREATE INDEX IF NOT EXISTS idx_app_users_active ON app_users (is_active);
