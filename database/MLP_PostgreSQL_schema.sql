-- MLP / Flagman — PostgreSQL 16 schema
-- Applied automatically by Docker on first initialization of the database volume.
BEGIN;

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    unit VARCHAR(255) NOT NULL,
    min_threshold NUMERIC(19,3) NOT NULL DEFAULT 0,
    shelf_life_hours INTEGER,
    CONSTRAINT uq_products_name UNIQUE (name),
    CONSTRAINT ck_products_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_products_unit_nonempty CHECK (length(btrim(unit)) > 0),
    CONSTRAINT ck_products_min_threshold_nonnegative CHECK (min_threshold >= 0),
    CONSTRAINT ck_products_shelf_life_positive CHECK (shelf_life_hours IS NULL OR shelf_life_hours > 0)
);

CREATE TABLE IF NOT EXISTS dishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(12,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dishes_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_dishes_price_nonnegative CHECK (price >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_dishes_name_ci ON dishes (lower(name));

CREATE TABLE IF NOT EXISTS batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supply_id VARCHAR(255) NOT NULL,
    product_id BIGINT NOT NULL REFERENCES products(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    quantity NUMERIC(19,3) NOT NULL,
    remaining_quantity NUMERIC(19,3) NOT NULL,
    supply_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expiration_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_batches_supply_id_nonempty CHECK (length(btrim(supply_id)) > 0),
    CONSTRAINT ck_batches_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_batches_remaining_valid CHECK (remaining_quantity >= 0 AND remaining_quantity <= quantity),
    CONSTRAINT ck_batches_expiration_after_supply CHECK (expiration_date > supply_date)
);
CREATE INDEX IF NOT EXISTS idx_batch_product_exp ON batches(product_id, expiration_date) WHERE remaining_quantity > 0;
CREATE INDEX IF NOT EXISTS idx_batches_supply_id ON batches(supply_id);
CREATE INDEX IF NOT EXISTS idx_batches_expiration_active ON batches(expiration_date) WHERE remaining_quantity > 0;

CREATE TABLE IF NOT EXISTS recipe_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id BIGINT NOT NULL REFERENCES dishes(id) ON UPDATE RESTRICT ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    required_quantity NUMERIC(19,3) NOT NULL,
    CONSTRAINT ck_recipe_required_quantity_positive CHECK (required_quantity > 0),
    CONSTRAINT uq_recipe_dish_product UNIQUE (dish_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_recipe_product ON recipe_items(product_id);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(40) NOT NULL,
    rejection_reason VARCHAR(255),
    CONSTRAINT ck_orders_status CHECK (status IN ('CREATED', 'COMPLETED', 'CANCELLED_OUT_OF_STOCK')),
    CONSTRAINT ck_orders_number_nonempty CHECK (length(btrim(order_number)) > 0)
);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status_created_at ON orders(status, created_at DESC);

CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON UPDATE RESTRICT ON DELETE CASCADE,
    dish_id BIGINT NOT NULL REFERENCES dishes(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    CONSTRAINT ck_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT uq_order_items_order_dish UNIQUE (order_id, dish_id)
);
CREATE INDEX IF NOT EXISTS idx_order_items_dish ON order_items(dish_id);

CREATE TABLE IF NOT EXISTS write_off_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES batches(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    quantity NUMERIC(19,3) NOT NULL,
    write_off_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    reason VARCHAR(40) NOT NULL,
    CONSTRAINT ck_write_off_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_write_off_reason CHECK (reason IN ('EXPIRED', 'SOLD', 'MANUAL_ADJUSTMENT', 'SPOILAGE', 'KITCHEN_ERROR', 'STAFF_MEAL'))
);
CREATE INDEX IF NOT EXISTS idx_wol_date ON write_off_logs(write_off_date DESC);
CREATE INDEX IF NOT EXISTS idx_write_off_batch ON write_off_logs(batch_id);

-- Read models for warehouse screens and reporting. They do not duplicate stored stock.
CREATE OR REPLACE VIEW v_stock_by_product AS
SELECT p.id AS product_id, p.name AS product_name, p.unit,
       p.min_threshold,
       COALESCE(SUM(b.remaining_quantity) FILTER (WHERE b.expiration_date > CURRENT_TIMESTAMP), 0)::NUMERIC(19,3) AS available_quantity,
       COALESCE(SUM(b.remaining_quantity) FILTER (WHERE b.expiration_date <= CURRENT_TIMESTAMP), 0)::NUMERIC(19,3) AS expired_quantity,
       MIN(b.expiration_date) FILTER (WHERE b.remaining_quantity > 0 AND b.expiration_date > CURRENT_TIMESTAMP) AS nearest_expiration,
       COALESCE(SUM(b.remaining_quantity) FILTER (WHERE b.remaining_quantity > 0 AND b.expiration_date > CURRENT_TIMESTAMP AND b.expiration_date <= CURRENT_TIMESTAMP + INTERVAL '48 hours'), 0)::NUMERIC(19,3) AS expiring_48h_quantity
FROM products p LEFT JOIN batches b ON b.product_id = p.id
GROUP BY p.id, p.name, p.unit, p.min_threshold;

CREATE OR REPLACE VIEW v_active_batches AS
SELECT b.id AS batch_id, b.supply_id, b.product_id, p.name AS product_name, p.unit,
       b.quantity, b.remaining_quantity, b.supply_date, b.expiration_date,
       GREATEST(0, FLOOR(EXTRACT(EPOCH FROM (b.expiration_date - CURRENT_TIMESTAMP)) / 3600))::BIGINT AS hours_until_expiration,
       (b.expiration_date <= CURRENT_TIMESTAMP) AS is_expired
FROM batches b JOIN products p ON p.id = b.product_id
WHERE b.remaining_quantity > 0;

COMMIT;
